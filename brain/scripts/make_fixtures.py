#!/usr/bin/env python3
"""Generate synthetic screenshots in brain/fixtures/ (+ fixtures.json with ground truth and
the geometry used, so tests don't depend on later calibration of config/).

    python scripts/make_fixtures.py [--scale 1.0]
"""
from __future__ import annotations

import argparse
import json
from dataclasses import asdict
from pathlib import Path

from PIL import Image

from dofus_brain.config import load_json
from dofus_brain.mock_render import DEFAULT_DIALOG, DEFAULT_FIGHT, Renderer

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--scale", type=float, default=1.0, help="capture pixels per window point (2.0 = Retina)")
    ap.add_argument("--out", default=str(ROOT / "fixtures"))
    a = ap.parse_args()
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    grid = load_json("grid", ROOT / "config")
    regions = load_json("regions", ROOT / "config")
    r = Renderer(grid, regions, scale=a.scale)
    shots = {
        "world_4_-18.png": ("world", r.world((4, -18))),
        "world_5_-18.png": ("world", r.world((5, -18))),
        "fight.png": ("fight", r.fight(DEFAULT_FIGHT)),
        "dialog.png": ("dialog", r.dialog(DEFAULT_DIALOG["npc"], DEFAULT_DIALOG["text"], DEFAULT_DIALOG["options"])),
        "loading.png": ("loading", r.loading()),
        "popup.png": ("popup", r.popup()),
    }
    for name, (_, img) in shots.items():
        Image.fromarray(img).save(out / name, optimize=True)
    meta = {
        "_comment": "Generated by scripts/make_fixtures.py. Ground truth for tests + the geometry the images were drawn with.",
        "window_points": [1280, 800],
        "scale": a.scale,
        "grid": {k: v for k, v in grid.items() if not k.startswith("_")},
        "regions": {k: v for k, v in regions.items() if not k.startswith("_")},
        "screens": {name: kind for name, (kind, _) in shots.items()},
        "world": {"world_4_-18.png": [4, -18], "world_5_-18.png": [5, -18], "hp": "250/250", "pa": 6, "pm": 3},
        "fight": asdict(DEFAULT_FIGHT),
        "dialog": DEFAULT_DIALOG,
    }
    (out / "fixtures.json").write_text(json.dumps(meta, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {len(shots)} fixtures to {out}")


if __name__ == "__main__":
    main()
